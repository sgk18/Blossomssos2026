/**
 * Calculates dynamic summary statistics directly from the schedule dataset.
 * Does not hardcode summary totals.
 */
export function getScheduleOverview(events: ScheduleEvent[] = BLOSSOMS_SCHEDULE_2026) {
  if (events.length === 0) {
    return {
      startDateFormatted: 'N/A',
      endDateFormatted: 'N/A',
      totalEventDays: 0,
      totalEvents: 0,
      uniqueVenuesCount: 0,
    };
  }

  // Sort dates to determine exact chronological boundary
  const sortedDates = Array.from(new Set(events.map((e) => e.date))).sort();
  const firstDate = new Date(`${sortedDates[0]}T00:00:00`);
  const lastDate = new Date(`${sortedDates[sortedDates.length - 1]}T00:00:00`);

  const formatDate = (d: Date) =>
    d.toLocaleDateString('en-US', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    });

  const uniqueVenues = new Set(events.map((e) => e.venue));

  return {
    startDateFormatted: formatDate(firstDate),
    endDateFormatted: formatDate(lastDate),
    totalEventDays: sortedDates.length,
    totalEvents: events.length,
    uniqueVenuesCount: uniqueVenues.size,
  };
}

/**
 * Groups events chronologically by date.
 */
export function groupEventsByDate(events: ScheduleEvent[]): Record<string, ScheduleEvent[]> {
  const groups: Record<string, ScheduleEvent[]> = {};
  
  // Sort events chronologically
  const sorted = [...events].sort((a, b) => {
    if (a.date !== b.date) {
      return a.date.localeCompare(b.date);
    }
    // Same day: sort by start time if available
    return (a.startTime24 || '00:00').localeCompare(b.startTime24 || '00:00');
  });

  sorted.forEach((event) => {
    if (!groups[event.date]) {
      groups[event.date] = [];
    }
    groups[event.date].push(event);
  });

  return groups;
}
